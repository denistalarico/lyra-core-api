import type { PublisherCapabilities } from '../provider-capabilities';

/**
 * TikTok accounts authorized through the TikTok API for Business app (the same
 * app as TikTok Ads, "TikTok Accounts" permission). A distinct provider key,
 * like Instagram Login next to Facebook Login: its tokens only work on
 * `business-api.tiktok.com` and must never be resolved as a Login Kit asset.
 */
export const TIKTOK_BUSINESS_PROVIDER = 'tiktok_business';
export const TIKTOK_BUSINESS_ACCOUNT_ASSET_TYPE = 'tiktok_business_account';

/**
 * Scopes are chosen on the app page, not in the request: the authorization URL
 * is generated by TikTok. These are the ones Lyra needs (DOCUMENTED 2026-11-17,
 * Accounts API authentication example).
 */
export const SOCIAL_TIKTOK_BUSINESS_SCOPES = [
  'user.info.basic',
  'user.info.username',
  'user.info.stats',
  'video.publish',
  'video.list',
] as const;

/** DOCUMENTED 2026-11-17 (`/business/video/publish/`): 1 GB, 3–600 s. */
const MAX_VIDEO_BYTES = 1024 * 1024 * 1024;

/**
 * `/business/video/publish/` (v1.3): one public video from a verified URL.
 * Scheduling is Lyra's queue (the endpoint publishes immediately). No removal.
 */
export const TIKTOK_BUSINESS_ACCOUNT_CAPABILITIES: PublisherCapabilities = {
  provider: TIKTOK_BUSINESS_PROVIDER,
  assetType: TIKTOK_BUSINESS_ACCOUNT_ASSET_TYPE,
  placements: ['video'],
  media: {
    video: {
      acceptedMimeTypes: ['video/mp4', 'video/quicktime', 'video/webm'],
      maxBytes: MAX_VIDEO_BYTES,
      maxItemsPerPost: 1,
    },
  },
  supportsScheduling: true,
  supportsCaption: true,
  supportsFirstComment: false,
  supportsHashtags: true,
  requiresReconciliation: true,
  supportsRemoval: false,
};
